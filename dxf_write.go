// dxf_write.go 实现 ASCII DXF 写出（WriteDXF）：将解析后的 Document 导出为
// R2000 风格的 ASCII DXF（HEADER/TABLES/BLOCKS/ENTITIES/EOF 段）。
//
// 组码与值格式严格对齐 LibreDWG out_dxf.c 的输出约定：
//   - 组码行右对齐 3 字符，行尾 CRLF（\r\n）
//   - 浮点（组码 10-59/110-149/210-239/460-469 等）：%0.16G，NaN/Inf 归零，
//     纯整数值追加 ".0"（对齐 dxf_print_rd）
//   - 整数按组码区间定宽：60-79/170-179/270-299/370-409 用 %6i，
//     80-99/420-449 用 %9i，160-169/450-459 用 %12i（对齐 dxf_format）
//   - 句柄（5/330/340 等）：大写十六进制（FMT_H = %PRIX64）
//   - 角度组码 50-54 以度输出（对齐 VALUE_BD 的 rad2deg 分支）
//   - 实体公共头顺序：0 类型 → 5 句柄 → 330 owner → 100 AcDbEntity →
//     [67] → 8 图层 → 62/420 颜色 → 100 子类
//     （对齐 common_entity_handle_data.spec + common_entity_data.spec）
//
// 覆盖实体（与渲染同源的模型空间主力实体）：LINE/CIRCLE/ARC/POINT/ELLIPSE/
// LWPOLYLINE/TEXT/MTEXT/INSERT/ATTRIB/SOLID/TRACE/3DFACE/RAY/XLINE/SPLINE/
// HATCH（含渐变段与种子点）/DIMENSION(7 类)/LEADER/MLINE/
// POLYLINE_2D/3D/PFACE/MESH(含 VERTEX/SEQEND 聚合)/SHAPE/TOLERANCE/
// VIEWPORT/IMAGE/WIPEOUT/REGION/3DSOLID/BODY(SAT 文本)/OLE2FRAME/
// PROXY_ENTITY。已知取舍：ACIS SAB（version=2）无 SAT1 转换器跳过数据段
// （骨架保留）；PROXY class_id/objids 与 OLE oleclient/框对角不在模型中
// 省略；MLEADER 块内容经 ctx 段还原。
//
// 已知限制：解析路径未保留线型名与文字样式名，写出时按固定值合成
// （线型 ByBlock/ByLayer/Continuous、样式 Standard）；图层名/块名/块基点
// 按 layerColors[].name 与 internalObjects[BLOCK_HEADER] 真值写出，缺失时
// 兜底合成（图层 LAYER_<HEX>、块 *B<HEX>、基点 0,0,0）。pre-R13 文档同样
// 按 R2000 风格写出，$ACADVER 输出 AC1015 以保持文件自洽；其图纸空间实体
// 以 67=1 输出且按句柄去重。
package cad

import (
	"bufio"
	"errors"
	"fmt"
	"github.com/unitedrhino/go-cad/internal/container"
	"io"
	"math"
	"strconv"
	"strings"
)

// WriteDXF 将文档导出为 ASCII DXF 写入 w（R2000 风格段结构）。
func WriteDXF(doc *Document, w io.Writer) error {
	if doc == nil {
		return errors.New("cad: 文档为空，无法写出 DXF")
	}
	x := &dxfWriter{
		w:     bufio.NewWriter(w),
		alloc: newDXFHandleAlloc(doc),
		verts: newDXFVertexIndex(doc),
		doc:   doc,
	}
	x.str(999, "Generated by share/cad WriteDXF (LibreDWG out_dxf aligned)")
	x.writeHeader(doc)
	x.writeTables(doc)
	x.writeBlocks(doc)
	// 模型空间实体（含最大块启发式并入的内容）
	x.writeEntities(doc.modelSpaceEntities(), false)
	// pre-R13 图纸空间实体：67=1 标记，按句柄去重避免与模型空间重复
	if len(doc.pspaceSpace) > 0 {
		list := dedupeByHandle(doc.modelSpaceEntities(), doc.pspaceSpace)
		if len(list) > 0 {
			x.str(0, "SECTION")
			x.str(2, "ENTITIES")
			x.writeEntityList(list, true)
			x.str(0, "ENDSEC")
		}
	}
	x.str(0, "EOF")
	x.err = x.w.Flush()
	return x.err
}

// dedupeByHandle 返回 base 中未出现在 prev 句柄集合里的实体（顺序保持）。
func dedupeByHandle(prev, base []any) []any {
	seen := map[uint64]bool{}
	for _, e := range prev {
		if b := entBase(e); b != nil {
			seen[b.handle] = true
		}
	}
	var out []any
	for _, e := range base {
		b := entBase(e)
		if b == nil || seen[b.handle] {
			continue
		}
		seen[b.handle] = true
		out = append(out, e)
	}
	return out
}

// dxfWriter DXF 组码写出器：累计首个错误，后续调用变为空操作。
type dxfWriter struct {
	w     *bufio.Writer
	err   error
	alloc *dxfHandleAlloc
	verts *dxfVertexIndex
	doc   *Document // 真名/块基点消费源（layerColors/internalObjects）
	vpID  uint16    // VIEWPORT 69 组码 id 自增器（R2000+ 口径）
}

// fail 记录首个错误。
func (x *dxfWriter) fail(err error) {
	if x.err == nil {
		x.err = err
	}
}

// code 仅写组码行（"%3d\r\n"）。
func (x *dxfWriter) code(code int) {
	if x.err != nil {
		return
	}
	if _, err := fmt.Fprintf(x.w, "%3d\r\n", code); err != nil {
		x.fail(err)
	}
}

// val 写组码行 + 原样值行。
func (x *dxfWriter) val(code int, val string) {
	x.code(code)
	if x.err != nil {
		return
	}
	if _, err := x.w.WriteString(val); err != nil {
		x.fail(err)
		return
	}
	if _, err := x.w.WriteString("\r\n"); err != nil {
		x.fail(err)
	}
}

// str 写字符串组码：空串按 out_dxf.c VALUE 约定输出 "0"；
// 值内的 CR/LF 展平为空格保证 DXF 值恒单行。
func (x *dxfWriter) str(code int, s string) {
	s = dxfSanitizeText(s)
	if s == "" {
		s = "0"
	}
	x.val(code, s)
}

// dxfSanitizeText 展平字符串中的换行符（DXF 每个组码值必须单行）。
func dxfSanitizeText(s string) string {
	if !strings.ContainsAny(s, "\r\n") {
		return s
	}
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\r", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}

// flt 写浮点组码：对齐 out_dxf.c 的 dxf_print_rd——
// %0.16G 格式化、NaN/Inf 归零、纯整数值补 ".0"。
func (x *dxfWriter) flt(code int, v float64) {
	x.val(code, dxfFormatFloat(v))
}

// dxfFormatFloat 对齐 LibreDWG（DXF_PRECISION=16）的浮点格式化。
func dxfFormatFloat(v float64) string {
	if math.IsNaN(v) || math.IsInf(v, 0) {
		v = 0 // 错位解码常产生非法值，写出 0 保证 DXF 可读
	}
	s := strconv.FormatFloat(v, 'G', 16, 64)
	t := strings.TrimPrefix(s, "-")
	// C 实现仅对“纯数字”结果补 .0（含指数或特殊值不补）
	if t != "" && !strings.ContainsAny(t, ".Ee") {
		s += ".0"
	}
	return s
}

// int 写整数组码：按组码区间套用 out_dxf.c dxf_format 的定宽格式。
func (x *dxfWriter) int(code int, v int64) {
	width := dxfIntWidth(code)
	if width > 0 {
		x.val(code, fmt.Sprintf("%*d", width, v))
		return
	}
	x.val(code, strconv.FormatInt(v, 10))
}

// dxfIntWidth 组码 → 整数值行宽度（0 为不定宽），对齐 dxf_format。
func dxfIntWidth(code int) int {
	switch {
	case code >= 60 && code < 80, // BS/BL 计数与标志
		code >= 170 && code < 180,
		code >= 270 && code < 300,
		code >= 370 && code < 410,
		code >= 1060 && code <= 1070:
		return 6
	case code >= 80 && code < 100, // BL
		code >= 420 && code < 450, // int32
		code == 1071:
		return 9
	case code >= 160 && code < 170, // BLL
		code >= 450 && code < 460: // long
		return 12
	}
	return 0
}

// hex 写句柄组码：大写十六进制（FMT_H = %PRIX64）。
func (x *dxfWriter) hex(code int, h uint64) {
	x.val(code, strconv.FormatUint(h, 16))
}

// pt3 写 3D 点三行（10/20/30 起按偏移）。
func (x *dxfWriter) pt3(code int, p point3) {
	x.flt(code, p.x)
	x.flt(code+10, p.y)
	x.flt(code+20, p.z)
}

// pt2 写 2D 点两行（10/20 起按偏移）。
func (x *dxfWriter) pt2(code int, p point2) {
	x.flt(code, p.x)
	x.flt(code+10, p.y)
}

// vec3 写方向/挤出向量三行（210/220/230 起按偏移）。
func (x *dxfWriter) vec3(code int, p point3) {
	x.flt(code, p.x)
	x.flt(code+10, p.y)
	x.flt(code+20, p.z)
}

// radDeg 写角度组码（50-54）：弧度 → 度（对齐 VALUE_BD 的 rad2deg 分支）。
func (x *dxfWriter) radDeg(code int, rad float64) {
	x.flt(code, rad2deg(rad))
}

// ---- HEADER 段 ----

// writeHeader HEADER 段：版本、代码页、插入基点与图幅范围。
func (x *dxfWriter) writeHeader(doc *Document) {
	x.str(0, "SECTION")
	x.str(2, "HEADER")

	x.str(9, "$ACADVER")
	x.str(1, dxfTargetVersion(doc))
	x.str(9, "$DWGCODEPAGE")
	x.str(3, dxfCodepageName(doc.codepage))
	x.str(9, "$INSBASE")
	x.pt3(10, point3{})

	minX, minY, maxX, maxY := docBounds(doc)
	x.str(9, "$EXTMIN")
	x.pt3(10, point3{minX, minY, 0})
	x.str(9, "$EXTMAX")
	x.pt3(10, point3{maxX, maxY, 0})

	x.str(0, "ENDSEC")
}

// dxfTargetVersion DXF 的 $ACADVER：R13+ 直接透传源版本（同版式）；
// pre-R13 源无对应现代 DXF 版式，统一写出为 R2000（AC1015）。
func dxfTargetVersion(doc *Document) string {
	if doc.version.PreR13() {
		return "AC1015"
	}
	return doc.version.VerString()
}

// dxfCodepageName 代码页 → DXF 代码页名（31/39 为简体中文 GBK，其余按
// windows-1252 家族处理，与解码口径 decodeCodepage 一致）。
func dxfCodepageName(cp uint16) string {
	switch cp {
	case 31, 39:
		return "ANSI_936"
	default:
		return "ANSI_1252"
	}
}

// docBounds 模型空间（含最大块启发式内容与 INSERT 展开）的 2D 包围盒：
// 复用渲染的 tessellator 展开与鲁棒包围盒（抗错位解码的离群坐标）；
// 空图时返回 (0,0,0,0)。
func docBounds(doc *Document) (minX, minY, maxX, maxY float64) {
	prims := newTessellator(doc).expandAll()
	if len(prims) == 0 {
		return 0, 0, 0, 0
	}
	bb := robustBounds(prims)
	if bb.invalid() {
		return 0, 0, 0, 0
	}
	return bb.minX, bb.minY, bb.maxX, bb.maxY
}

// ---- TABLES 段 ----

// writeTables TABLES 段：LTYPE（内建三件套，必须先于 LAYER）+ LAYER。
// 解析路径未保留符号表名，图层名按句柄合成、颜色取解析结果。
func (x *dxfWriter) writeTables(doc *Document) {
	x.str(0, "SECTION")
	x.str(2, "TABLES")

	// LTYPE 表：ByBlock/ByLayer/Continuous（对齐 dwg2dxf 的内建三件套）
	x.str(0, "TABLE")
	x.str(2, "LTYPE")
	x.hex(5, x.alloc.ltypeTable)
	x.hex(330, 0)
	x.str(100, "AcDbSymbolTable")
	x.int(70, 1)
	x.ltypeRecord(x.alloc.ltypeByBlock, "ByBlock", "")
	x.ltypeRecord(x.alloc.ltypeByLayer, "ByLayer", "")
	x.ltypeRecord(x.alloc.ltypeCont, "Continuous", "Solid line")
	x.str(0, "ENDTAB")

	// LAYER 表：0 层恒存在 + 模型空间引用到的全部图层
	layers := dxfCollectLayers(doc)
	x.str(0, "TABLE")
	x.str(2, "LAYER")
	x.hex(5, x.alloc.layerTable)
	x.hex(330, 0)
	x.str(100, "AcDbSymbolTable")
	x.int(70, int64(len(layers)))
	for _, lr := range layers {
		x.str(0, "LAYER")
		x.hex(5, lr.handle)
		x.hex(330, x.alloc.layerTable)
		x.str(100, "AcDbSymbolTableRecord")
		x.str(100, "AcDbLayerTableRecord")
		x.str(2, lr.name)
		x.int(70, 0)
		// 颜色语义与渲染取色同口径（layerRenderColor）：32 位值低 24 位
		// ≤0xFF 为 ACI 索引形（方法字节 0xC3/0xC1），写 group 62 索引色；
		// >0xFF 才是 RGB 真彩形，写 group 420。索引形误写 420 会把索引
		// 当真彩输出错误颜色（消防图层 ACI 1~8 彩色系实证）。
		if low := lr.trueColor & 0x00FFFFFF; lr.trueColor > 0 && low > 0xFF {
			x.int(420, int64(lr.trueColor))
		} else if lr.index != 0 && lr.index != 256 {
			x.int(62, int64(lr.index))
		} else {
			x.int(62, 7)
		}
		x.str(6, "Continuous")
	}
	x.str(0, "ENDTAB")

	x.str(0, "ENDSEC")
}

// dxfLayerRecord LAYER 表条目。
type dxfLayerRecord struct {
	handle    uint64
	name      string
	index     int64  // ACI 颜色索引（默认 7 白）
	trueColor uint32 // 真彩色（>0 时优先于索引）
}

// dxfLayerName 图层句柄 → 合成名（0 层为 "0"，其余 LAYER_<HEX>）；
// 仅供真名缺失时的兜底，写出侧统一走 dxfWriter.layerName。
func dxfLayerName(h uint64) string {
	if h == 0 {
		return "0"
	}
	return fmt.Sprintf("LAYER_%X", h)
}

// layerName 图层句柄 → 真名：LAYER 表记录解码保存的 name（DWG 扫描/
// 字符串流、JSON name 键、DXF LAYER 表均有）；缺失时按句柄合成。
func (x *dxfWriter) layerName(h uint64) string {
	if lc, ok := x.doc.layerColors[h]; ok && lc.name != "" {
		return lc.name
	}
	return dxfLayerName(h)
}

// dxfBlockRealName 块定义句柄 → BLOCK_HEADER 真名（DWG/JSON/DXF 三来源
// 均经 internalObjects 登记）；缺失返回空串。
func (x *dxfWriter) dxfBlockRealName(h uint64) string {
	if g := x.doc.internalObjects[h]; g != nil {
		if s, ok := g.Field("name").(string); ok {
			return s
		}
	}
	return ""
}

// blockName 块定义句柄 → DXF 块名：真名优先，无则按句柄合成。
func (x *dxfWriter) blockName(h uint64) string {
	if s := x.dxfBlockRealName(h); s != "" {
		return s
	}
	return dxfBlockName(h)
}

// blockBasePoint 块定义句柄 → BLOCK_HEADER 基点（组码 10/20/30）；
// 未解析（含全零）返回原点。JSON 来源的 base_pt 为 []any 数组形态。
func (x *dxfWriter) blockBasePoint(h uint64) point3 {
	g := x.doc.internalObjects[h]
	if g == nil {
		return point3{}
	}
	switch v := g.Field("base_pt").(type) {
	case []float64:
		if len(v) == 3 {
			return point3{v[0], v[1], v[2]}
		}
	case []any:
		if len(v) == 3 {
			x0, _ := v[0].(float64)
			y0, _ := v[1].(float64)
			z0, _ := v[2].(float64)
			return point3{x0, y0, z0}
		}
	}
	return point3{}
}

// dxfCollectLayers 汇总 LAYER 表条目：先保证 0 层，再收解析到的颜色表与
// 实体实际引用的图层句柄。
func dxfCollectLayers(doc *Document) []dxfLayerRecord {
	seen := map[uint64]bool{}
	out := []dxfLayerRecord{{handle: 0, name: "0", index: 7}}
	seen[0] = true
	add := func(h uint64) {
		if seen[h] {
			return
		}
		seen[h] = true
		rec := dxfLayerRecord{handle: h, name: dxfLayerName(h), index: 7}
		if lc, ok := doc.layerColors[h]; ok {
			if lc.name != "" {
				rec.name = lc.name
			}
			if lc.hasTrue {
				rec.trueColor = lc.trueColor & 0x00FFFFFF
			} else if lc.index != 0 {
				rec.index = int64(lc.index)
			}
		}
		out = append(out, rec)
	}
	for h := range doc.layerColors {
		add(h)
	}
	for _, ent := range doc.modelSpaceEntities() {
		if b := entBase(ent); b != nil {
			add(b.layer)
		}
	}
	return out
}

// ltypeRecord 输出单个 LTYPE 表记录（3 描述、72 对齐码 65、73 划线数 0）。
func (x *dxfWriter) ltypeRecord(handle uint64, name, desc string) {
	x.str(0, "LTYPE")
	x.hex(5, handle)
	x.hex(330, x.alloc.ltypeTable)
	x.str(100, "AcDbSymbolTableRecord")
	x.str(100, "AcDbLinetypeTableRecord")
	x.str(2, name)
	x.int(70, 0)
	x.str(3, desc)
	x.int(72, 65)
	x.int(73, 0)
	x.flt(40, 0)
}

// ---- BLOCKS 段 ----

// dxfBlockName 块定义句柄 → 合成块名（INSERT 组码 2 与 BLOCKS 段共用）。
func dxfBlockName(blockHeader uint64) string {
	return fmt.Sprintf("*B%X", blockHeader)
}

// dxfHandleAlloc 合成句柄分配器：从文档最大句柄之后顺序分配，避免与
// 真实句柄空间冲突。保留位依次为模型/图纸空间 BLOCK_RECORD、内建 LTYPE
// 三件套与两张表头；动态位（SEQEND/ENDBLK/*Model_Space 块标记）随后递增。
type dxfHandleAlloc struct {
	next         uint64 // 下一个可分配句柄
	msRecord     uint64 // 模型空间 BLOCK_RECORD（实体 330）
	psRecord     uint64 // 图纸空间 BLOCK_RECORD
	ltypeTable   uint64 // LTYPE 表头
	ltypeByBlock uint64 // 内建线型 ByBlock
	ltypeByLayer uint64 // 内建线型 ByLayer
	ltypeCont    uint64 // 内建线型 Continuous
	layerTable   uint64 // LAYER 表头
}

// newDXFHandleAlloc 扫描全文档实体/属性取最大句柄，并在其后分配保留位
// （封顶防越界）。
func newDXFHandleAlloc(doc *Document) *dxfHandleAlloc {
	maxH := uint64(0)
	bump := func(h uint64) {
		if h > maxH && h < 0xFFFFFF00 {
			maxH = h
		}
	}
	for _, list := range [][]any{doc.modelSpace, doc.pspaceSpace} {
		for _, ent := range list {
			if b := entBase(ent); b != nil {
				bump(b.handle)
			}
		}
	}
	for _, list := range doc.blocks {
		for _, ent := range list {
			if b := entBase(ent); b != nil {
				bump(b.handle)
			}
		}
	}
	for h := range doc.attribs {
		bump(h)
	}
	a := &dxfHandleAlloc{next: maxH}
	a.msRecord = a.take()
	a.psRecord = a.take()
	a.ltypeTable = a.take()
	a.ltypeByBlock = a.take()
	a.ltypeByLayer = a.take()
	a.ltypeCont = a.take()
	a.layerTable = a.take()
	return a
}

// take 分配下一个合成句柄。
func (a *dxfHandleAlloc) take() uint64 {
	a.next++
	return a.next
}

// writeBlocks BLOCKS 段：*Model_Space 空块对 + 各块定义（内容实体）。
// 最大块内容已并入 ENTITIES 段（模型空间启发式）；以 POLYLINE 实体句柄为
// key 的“伪块”（POLYLINE 顶点按 owner 归类产生）跳过——顶点已由
// ENTITIES 段的 POLYLINE 聚合输出，此处再输出会与 POLYLINE 句柄撞车。
func (x *dxfWriter) writeBlocks(doc *Document) {
	x.str(0, "SECTION")
	x.str(2, "BLOCKS")

	// *Model_Space：内容在 ENTITIES 段，块对恒空（对齐 dwg2dxf）
	x.blockBegin(x.alloc.take(), x.alloc.msRecord, "*Model_Space", point3{})
	x.blockEnd(x.alloc.take(), x.alloc.msRecord)

	largest := doc.largestBlockHeader()
	pseudo := dxfPseudoBlockKeys(doc)
	for h, list := range doc.blocks {
		if h == largest || pseudo[h] {
			continue
		}
		// BLOCK 标记实体用合成句柄：blocks key 来自 ownerhandle 归类，
		// 可能与实体句柄撞车；DXF 中 INSERT↔BLOCK 靠名字（组码 2）关联
		x.blockBegin(x.alloc.take(), x.alloc.msRecord, x.blockName(h), x.blockBasePoint(h))
		x.writeEntityList(list, false)
		x.blockEnd(x.alloc.take(), x.alloc.msRecord)
	}

	x.str(0, "ENDSEC")
}

// dxfPseudoBlockKeys 收集“伪块”key：全部 POLYLINE 实体句柄（其顶点在
// 解析归类时以 owner=POLYLINE 句柄落入 blocks 表）。PFACE/MESH 同理——
// 顶点由 ENTITIES 段的 POLYLINE 聚合输出，块段再输出会产生孤立 VERTEX。
func dxfPseudoBlockKeys(doc *Document) map[uint64]bool {
	out := map[uint64]bool{}
	for _, list := range [][]any{doc.modelSpace, doc.pspaceSpace} {
		for _, ent := range list {
			switch ent.(type) {
			case *entPolyline2d, *entPolyline3d, *entPolylinePface, *entPolylineMesh:
				if b := entBase(ent); b != nil {
					out[b.handle] = true
				}
			}
		}
	}
	return out
}

