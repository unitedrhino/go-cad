// dxfLongText 输出 MTEXT 文本：超 250 字节按 DXF 惯例拆为 3（前段）+ 1（尾段），
// 切分点回退到 UTF-8 字符边界。
func (x *dxfWriter) dxfLongText(text string) {
	const chunk = 250
	b := []byte(text)
	if len(b) <= chunk {
		x.str(1, text)
		return
	}
	cut := chunk
	for cut > 0 && b[cut]&0xC0 == 0x80 {
		cut--
	}
	x.str(3, string(b[:cut]))
	x.str(1, string(b[cut:]))
}

